#!/usr/bin/env python
"""Set the atomic weights in seamm_util/elemental_data.py from mendeleev.

    python devtools/elemental_weights_from_mendeleev.py

The atomic weight of each element is mendeleev's standard atomic weight -- for the
elements whose weight varies in nature, the conventional value (Li 6.94, not the
midpoint of [6.938, 6.997]). For an element with no standard atomic weight, which
mendeleev gives as the mass number of its representative isotope (Ra 226), it is the
mass of that isotope (226.025408186). Only "atomic weight" and "source" change; the
other fields are kept. The file is rewritten and formatted with black.
tests/test_elemental_data.py checks the table against mendeleev.
"""

from pathlib import Path
import subprocess

import mendeleev
from mendeleev.fetch import fetch_table

from seamm_util.elemental_data import element_data

HEADER = '''"""Tabulated data about the elements."""

# The atomic weights are mendeleev's ({version}): the standard atomic weights, with
# the conventional value for the elements whose weight varies in nature (Li 6.94,
# Ar 39.948), and for elements with no standard atomic weight the mass of the
# representative isotope (Ra-226 226.025408186). Generated by
# devtools/elemental_weights_from_mendeleev.py; do not edit them by hand.
# molsystem.elements uses this table too.
'''


def weights():
    """{symbol: (weight, source)} from mendeleev."""
    elements = fetch_table("elements")
    isotopes = fetch_table("isotopes")
    result = {}
    for _, row in elements.iterrows():
        w = float(row.atomic_weight)
        source = f"mendeleev {mendeleev.__version__}: standard atomic weight"
        if abs(w - round(w)) < 1.0e-9:
            a = int(round(w))
            isotope = isotopes[
                (isotopes.atomic_number == row.atomic_number)
                & (isotopes.mass_number == a)
            ]
            if not isotope.empty:
                w = float(isotope.mass.iloc[0])
                source = (
                    f"mendeleev {mendeleev.__version__}: mass of {a}{row.symbol}, "
                    "the representative isotope"
                )
        result[row.symbol] = (w, source)
    return result


